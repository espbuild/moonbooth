import { mkdir, readFile, writeFile, appendFile } from "node:fs/promises";
import path from "node:path";
import type {
  ModelReport,
  RuntimeDef,
  SessionRequest,
  SessionResult,
  StubOp,
} from "../types.js";
import { NOT_REPORTED } from "../types.js";

// The stub adapter: a deterministic, scripted stand-in for a model.
// It performs exactly the file operations listed in the step's script,
// so tests and smoke runs exercise the full harness pipeline — engine,
// conditions, driver, checks, manifests — at zero model cost. Its
// behavior is scripted, not agentic; exports say so in their
// limitations, and stub results are never evidence about models.

interface ContractDoc {
  version: number;
  itemsResponse: { shape: "offset" | "cursor"; fields: string[] };
}

async function readContract(workspace: string): Promise<ContractDoc> {
  const raw = await readFile(path.join(workspace, "contract", "api.json"), "utf8");
  const doc = JSON.parse(raw) as ContractDoc;
  if (typeof doc.version !== "number" || !doc.itemsResponse?.shape) {
    throw new Error("contract/api.json is missing version or itemsResponse.shape");
  }
  return doc;
}

function serviceSource(shape: "offset" | "cursor"): string {
  if (shape === "offset") {
    return `// Generated by the stub adapter from contract shape "offset".
import { ITEMS } from "../data/items.mjs";

export const SERVICE_SHAPE = "offset";

export function createItemsService() {
  return {
    list(request) {
      const offset = request.offset ?? 0;
      const limit = request.limit ?? ITEMS.length;
      return {
        items: ITEMS.slice(offset, offset + limit),
        total: ITEMS.length,
      };
    },
  };
}
`;
  }
  return `// Generated by the stub adapter from contract shape "cursor".
import { ITEMS } from "../data/items.mjs";

export const SERVICE_SHAPE = "cursor";

export function createItemsService() {
  return {
    list(request) {
      const start = request.cursor == null ? 0 : Number(request.cursor);
      const limit = request.limit ?? ITEMS.length;
      const end = Math.min(start + limit, ITEMS.length);
      return {
        items: ITEMS.slice(start, end),
        nextCursor: end < ITEMS.length ? String(end) : null,
      };
    },
  };
}
`;
}

function clientSource(shape: "offset" | "cursor"): string {
  if (shape === "offset") {
    return `// Generated by the stub adapter from contract shape "offset".
export const CLIENT_SHAPE = "offset";

export function fetchAllItems(service, pageSize) {
  const collected = [];
  let offset = 0;
  for (;;) {
    const page = service.list({ offset, limit: pageSize });
    collected.push(...page.items);
    offset += page.items.length;
    if (collected.length >= page.total || page.items.length === 0) break;
  }
  return collected;
}
`;
  }
  return `// Generated by the stub adapter from contract shape "cursor".
export const CLIENT_SHAPE = "cursor";

export function fetchAllItems(service, pageSize) {
  const collected = [];
  let cursor = null;
  for (;;) {
    const page = service.list({ cursor, limit: pageSize });
    collected.push(...page.items);
    cursor = page.nextCursor;
    if (cursor == null) break;
  }
  return collected;
}
`;
}

export class StubAdapter {
  readonly kind = "stub";
  constructor(private readonly runtime: RuntimeDef) {}

  describe(): ModelReport {
    return { provider: "labs-stub", model: "stub-scripted", revision: "deterministic-v1" };
  }

  async runSession(req: SessionRequest): Promise<SessionResult> {
    // A session with no script performs no operations.
    const script = req.script ?? [];
    const done: string[] = [];
    try {
      for (const op of script) {
        await this.applyOp(req, op);
        done.push(op.op);
        req.record("stub_op", { op: op.op });
      }
    } catch (err) {
      return {
        status: "failed",
        summary: `Stub script failed after ${done.length} op(s): ${err instanceof Error ? err.message : String(err)}`,
        usage: { inputTokens: NOT_REPORTED, outputTokens: NOT_REPORTED, costUsd: NOT_REPORTED, costMethod: "not reported" },
        model: this.describe(),
        failureCategory: "fixture_error",
      };
    }
    return {
      status: "completed",
      summary: `Stub performed ${done.length} scripted op(s): ${done.join(", ") || "none"}.`,
      usage: { inputTokens: NOT_REPORTED, outputTokens: NOT_REPORTED, costUsd: NOT_REPORTED, costMethod: "not reported" },
      model: this.describe(),
    };
  }

  private async applyOp(req: SessionRequest, op: StubOp): Promise<void> {
    const ws = req.workspace;
    switch (op.op) {
      case "writeServiceFromContract": {
        const contract = await readContract(ws);
        await this.write(ws, op.target, serviceSource(contract.itemsResponse.shape));
        break;
      }
      case "writeClientFromContract": {
        const contract = await readContract(ws);
        await this.write(ws, op.target, clientSource(contract.itemsResponse.shape));
        break;
      }
      case "writeFile":
        await this.write(ws, op.path, op.content);
        break;
      case "appendFile": {
        const dest = path.join(ws, op.path);
        await mkdir(path.dirname(dest), { recursive: true });
        await appendFile(dest, op.content, "utf8");
        break;
      }
      case "note":
        req.record("stub_note", { text: op.text });
        break;
    }
  }

  private async write(workspace: string, rel: string, content: string): Promise<void> {
    const dest = path.join(workspace, rel);
    await mkdir(path.dirname(dest), { recursive: true });
    await writeFile(dest, content, "utf8");
  }
}
